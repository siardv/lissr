.archive_fixture_bytes <- function(name) {
  value <- .archive_fixture_hex[[name]]
  if (is.null(value)) stop("unknown invented ZIP fixture")
  positions <- seq.int(1L, nchar(value), by = 2L)
  as.raw(strtoi(substring(value, positions, positions + 1L), base = 16L))
}

.archive_fixture_write <- function(name, path) {
  writeBin(.archive_fixture_bytes(name), path)
  invisible(path)
}

.archive_test_root <- function() {
  root <- tempfile("lissr_archive_test_")
  if (!dir.create(root)) stop("cannot create synthetic archive test root")
  root
}

.archive_read <- function(path) readBin(path, what = "raw", n = file.info(path)$size)

.archive_stage_names <- function(root) {
  list.files(root, pattern = "^\\.lissr_unzip_", all.files = TRUE)
}
